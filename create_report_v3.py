def set_bg(cell, hex_color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcPr.append(shd)

def page_img(pdf_path, page_num, dpi=100):
    doc = fitz.open(pdf_path)
    page = doc[page_num]
    mat = fitz.Matrix(dpi/72, dpi/72)
    pix = page.get_pixmap(matrix=mat, colorspace=fitz.csRGB)
    img_bytes = pix.tobytes("jpeg", jpg_quality=72)
    doc.close()
    return io.BytesIO(img_bytes)

def h1(doc, text):
    p = doc.add_heading(text, level=1)
    for run in p.runs:
        run.font.size = Pt(14)
        run.font.color.rgb = RGBColor(0x1F, 0x49, 0x7D)
    return p

def h2(doc, text):
    p = doc.add_heading(text, level=2)
    for run in p.runs:
        run.font.size = Pt(12)
        run.font.color.rgb = RGBColor(0x2E, 0x74, 0xB5)
    return p

def h3(doc, text):
    p = doc.add_heading(text, level=3)
    for run in p.runs:
        run.font.size = Pt(10)
        run.font.color.rgb = RGBColor(0x1F, 0x49, 0x7D)
    return p

def body(doc, text, bold=False, italic=False, size=10, color=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    if color:
        r.font.color.rgb = RGBColor(*color)
    return p

def bullet(doc, text, size=10, color=None, bold=False):
    p = doc.add_paragraph(style='List Bullet')
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    if color:
        r.font.color.rgb = RGBColor(*color)
    return p

def box(doc, label, text, bg="FFE699", label_color=(0x7F,0x30,0x00)):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.style = 'Table Grid'
    cell = tbl.cell(0,0)
    set_bg(cell, bg)
    p = cell.paragraphs[0]
    if label:
        rl = p.add_run(label + " ")
        rl.font.bold = True
        rl.font.size = Pt(10)
        rl.font.color.rgb = RGBColor(*label_color)
    rt = p.add_run(text)
    rt.font.size = Pt(10)
    doc.add_paragraph()

def add_img(doc, pdf_path, page_num, caption, width=Inches(6)):
    try:
        stream = page_img(pdf_path, page_num)
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(stream, width=width)
        cap = doc.add_paragraph(caption)
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cap.runs[0].font.italic = True
        cap.runs[0].font.size = Pt(9)
        cap.runs[0].font.color.rgb = RGBColor(0x60,0x60,0x60)
    except:
        pass

def tbl_hdr(row, headers, bg="2E74B5"):
    for i, h in enumerate(headers):
        cell = row.cells[i]
        set_bg(cell, bg)
        p = cell.paragraphs[0]
        r = p.add_run(h)
        r.font.bold = True
        r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0xFF,0xFF,0xFF)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER

def cell_txt(cell, text, bold=False, sz=9, color=None, align=WD_ALIGN_PARAGRAPH.LEFT):
    p = cell.paragraphs[0]
    r = p.add_run(text)
    r.font.size = Pt(sz)
    r.font.bold = bold
    if color:
        r.font.color.rgb = RGBColor(*color)
    p.alignment = align

def stripe(table, start=1, c1="FFFFFF", c2="EBF3FB"):
    for i, row in enumerate(table.rows):
        if i < start:
            continue
        col = c1 if (i-start) % 2 == 0 else c2
        for cell in row.cells:
            set_bg(cell, col)

